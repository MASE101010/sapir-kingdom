-- The kingdom's live records. Resident n has house number n and stands on plot n - 1 (site/data/plan.json), for good.
CREATE TABLE IF NOT EXISTS residents (n INTEGER PRIMARY KEY AUTOINCREMENT, u TEXT NOT NULL UNIQUE, h TEXT NOT NULL, day INTEGER NOT NULL, src TEXT NOT NULL, at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS codes (code TEXT PRIMARY KEY, device TEXT NOT NULL, at INTEGER NOT NULL, u TEXT);
CREATE TABLE IF NOT EXISTS devices (device TEXT PRIMARY KEY, u TEXT NOT NULL, at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS comments (id TEXT PRIMARY KEY, media TEXT, u TEXT, text TEXT, at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS state (k TEXT PRIMARY KEY, v TEXT NOT NULL);
INSERT OR IGNORE INTO state (k, v) VALUES ('day', '1');
